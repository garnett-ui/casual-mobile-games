// Writes sw-manifest.js: the list of files the service worker precaches and
// a version hash of their contents. Run after changing any app file:
//   node tools/build-sw.mjs        (write)
//   node tools/build-sw.mjs --check (fail if out of date; used in CI)
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const INCLUDE = ['index.html', 'manifest.webmanifest', 'css', 'js', 'games', 'icons'];

function walk(p, out) {
  if (statSync(p).isDirectory()) {
    for (const f of readdirSync(p).sort()) walk(join(p, f), out);
  } else out.push(p);
}

const paths = [];
for (const p of INCLUDE) walk(join(root, p), paths);
const hash = createHash('sha256');
hash.update(readFileSync(join(root, 'sw.js')));
const files = ['./'];
for (const p of paths) {
  const rel = relative(root, p).split('\\').join('/');
  hash.update(rel);
  hash.update(readFileSync(p));
  files.push(rel);
}
const version = hash.digest('hex').slice(0, 12);
const out = `// Generated by tools/build-sw.mjs -- do not edit by hand.\nself.PRECACHE = ${JSON.stringify({ version, files }, null, 2)};\n`;
const target = join(root, 'sw-manifest.js');

if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== out) {
    console.error('sw-manifest.js is out of date. Run: node tools/build-sw.mjs');
    process.exit(1);
  }
  console.log(`sw-manifest.js up to date (${version}, ${files.length} files)`);
} else {
  writeFileSync(target, out);
  console.log(`wrote sw-manifest.js (${version}, ${files.length} files)`);
}
