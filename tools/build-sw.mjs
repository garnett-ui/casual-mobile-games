// Writes the generated build files from the source tree:
//   js/version.js   the app's semver version (from package.json)
//   sw-manifest.js  files the service worker precaches, the app version, and
//                   a hash of every file so any change yields a new cache
// Run after changing any app file or bumping the version:
//   node tools/build-sw.mjs          (write)
//   node tools/build-sw.mjs --check  (fail if out of date; used in CI)
import { createHash } from 'node:crypto';
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, relative } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const INCLUDE = ['index.html', 'manifest.webmanifest', 'css', 'js', 'games', 'icons'];
const check = process.argv.includes('--check');
let stale = false;

function emit(rel, content) {
  const target = join(root, rel);
  if (check) {
    if (!existsSync(target) || readFileSync(target, 'utf8') !== content) {
      console.error(`${rel} is out of date. Run: npm run build`);
      stale = true;
    }
  } else {
    writeFileSync(target, content);
  }
}

const { version: appVersion } = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
if (!/^\d+\.\d+\.\d+$/.test(appVersion)) throw new Error(`package.json version "${appVersion}" is not semver`);
const versionJs = `// Generated by tools/build-sw.mjs from package.json -- do not edit by hand.\nexport const VERSION = '${appVersion}';\n`;
emit('js/version.js', versionJs);

// The in-app version history (About box), from CHANGELOG.md: newest first,
// each version's bullet points as plain text with **bold** and *italics*.
const changelog = [];
for (const line of readFileSync(join(root, 'CHANGELOG.md'), 'utf8').split('\n')) {
  const head = line.match(/^## (\d+\.\d+\.\d+)/);
  if (head) changelog.push({ v: head[1], notes: [] });
  else if (changelog.length && line.startsWith('- ')) changelog.at(-1).notes.push(line.slice(2).trim());
  else if (changelog.length && /^\s+\S/.test(line) && changelog.at(-1).notes.length) {
    const notes = changelog.at(-1).notes;
    notes[notes.length - 1] += ` ${line.trim()}`;
  }
}
emit('js/changelog.js', `// Generated by tools/build-sw.mjs from CHANGELOG.md -- do not edit by hand.\nexport const CHANGELOG = ${JSON.stringify(changelog, null, 2)};\n`);

function walk(p, out) {
  if (statSync(p).isDirectory()) {
    for (const f of readdirSync(p).sort()) walk(join(p, f), out);
  } else out.push(p);
}

const paths = [];
for (const p of INCLUDE) walk(join(root, p), paths);
const hash = createHash('sha256');
hash.update(readFileSync(join(root, 'sw.js')));
hash.update(appVersion);
const files = ['./'];
for (const p of paths) {
  const rel = relative(root, p).split('\\').join('/');
  hash.update(rel);
  hash.update(rel === 'js/version.js' ? versionJs : readFileSync(p));
  files.push(rel);
}
const version = hash.digest('hex').slice(0, 12);
emit('sw-manifest.js', `// Generated by tools/build-sw.mjs -- do not edit by hand.\nself.PRECACHE = ${JSON.stringify({ appVersion, version, files }, null, 2)};\n`);

if (stale) process.exit(1);
console.log(`${check ? 'build files up to date' : 'wrote build files'}: v${appVersion} (${version}, ${files.length} files)`);
