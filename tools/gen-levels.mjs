// Generates games/car-jam/levels.js: the campaign, from tiny tutorial lots to
// big jammed ones. Every level is verified solvable and its par is the
// optimal move count found by the solver. Deterministic: same output each run.
//
//   node tools/gen-levels.mjs
import { writeFileSync } from 'node:fs';
import { generateLevel } from '../games/car-jam/model.js';
import { tierFor, LEVEL_COUNT } from '../games/car-jam/tiers.js';

const out = [];
for (let n = 1; n <= LEVEL_COUNT; n++) {
  const tier = tierFor(n);
  const level = generateLevel(n * 7919, tier.spec, tier.tries || 300);
  if (!level) throw new Error(`could not generate level ${n}`);
  const entry = { ...level, grannies: tier.grannies };
  if (tier.tip && tier.first === n) entry.tip = tier.tip;
  out.push(entry);
  console.log(`level ${n}: ${level.w}x${level.h} cars=${level.cars.length} par=${level.par}`);
}

const body = out.map((l) => '  ' + JSON.stringify(l)).join(',\n');
writeFileSync(
  new URL('../games/car-jam/levels.js', import.meta.url),
  `// Generated by tools/gen-levels.mjs -- do not edit by hand.\nexport default [\n${body},\n];\n`,
);
